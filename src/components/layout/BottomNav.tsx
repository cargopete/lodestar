// Flat list of all more items for active state detection
const allMoreItems = moreSections.flatMap((s) => s.items);

export function BottomNav() {
  const pathname = usePathname();
  const [showMore, setShowMore] = useState(false);

  const isMoreActive = allMoreItems.some(
    (item) => pathname === item.href || pathname.startsWith(item.href + '/')
  );

  return (
    <>
      {/* Sheet overlay */}
      {showMore && (
        <div
          className="fixed inset-0 bg-black/60 z-40 md:hidden backdrop-blur-sm"
          onClick={() => setShowMore(false)}
        />
      )}

      {/* More sheet — slides up from bottom */}
      <div
        className={cn(
          'fixed left-0 right-0 z-50 md:hidden transition-transform duration-300 ease-out',
          showMore ? 'translate-y-0' : 'translate-y-full'
        )}
        style={{ bottom: 'calc(var(--bottom-nav-height) + var(--safe-bottom))' }}
      >
        <div className="mx-2 mb-2 bg-[var(--bg-surface)] border border-[var(--border)] rounded-2xl shadow-[var(--shadow-float)] overflow-hidden">
          {/* Handle + header */}
          <div className="flex items-center justify-between px-4 pt-3 pb-2 border-b border-[var(--border)]">
            <span className="text-xs font-semibold text-[var(--text-faint)] uppercase tracking-wider">Navigate</span>
            <button
              onClick={() => setShowMore(false)}
              className="w-7 h-7 flex items-center justify-center rounded-full bg-[var(--bg-elevated)] text-[var(--text-faint)] active:scale-90 transition-transform"
            >
              <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
                <path strokeLinecap="round" strokeLinejoin="round" d="M6 18L18 6M6 6l12 12" />
              </svg>
            </button>
          </div>

          {/* Scrollable sections */}
          <div className="overflow-y-auto max-h-[calc(100svh-var(--bottom-nav-height)-var(--safe-bottom)-8rem)] px-3 py-3 space-y-4">
            {moreSections.map((section) => (
              <div key={section.title}>
                <p className="text-[10px] font-semibold text-[var(--text-faint)] uppercase tracking-widest mb-2 px-1">
                  {section.title}
                </p>
                <div className="grid grid-cols-3 gap-2">
                  {section.items.map((item) => {
                    const isActive = pathname === item.href || pathname.startsWith(item.href + '/');
                    return (
                      <Link
                        key={item.href}
                        href={item.href}
                        onClick={() => setShowMore(false)}
                        className={cn(
                          'flex flex-col items-center gap-1.5 py-3 px-1 rounded-xl border transition-all active:scale-95',
                          isActive
                            ? 'bg-[var(--accent-dim)] border-[var(--accent)]/30 text-[var(--accent)]'
                            : 'bg-[var(--bg-elevated)] border-transparent text-[var(--text-muted)] hover:text-[var(--text)] hover:bg-[var(--bg-elevated)]'
                        )}
                      >
                        {item.icon}
                        <span className="text-[10px] font-medium text-center leading-tight">{item.label}</span>
                      </Link>
                    );
                  })}
                </div>
              </div>
            ))}
          </div>
        </div>
      </div>

      {/* Bottom tab bar */}
      <nav
        className="fixed bottom-0 left-0 right-0 z-50 md:hidden bg-[var(--bg-surface)] border-t border-[var(--border)]"
        style={{ paddingBottom: 'var(--safe-bottom)' }}
      >
        <div className="flex items-center justify-around h-[var(--bottom-nav-height)]">
          {tabs.map((tab) => {
            const isActive = tab.href === '/'
              ? pathname === '/'
              : pathname.startsWith(tab.href);
            return (
              <Link
                key={tab.href}
                href={tab.href}
                className={cn(
                  'flex flex-col items-center justify-center gap-0.5 min-w-[56px] h-full px-2 transition-colors active:scale-[0.92]',
                  isActive ? 'text-[var(--accent)]' : 'text-[var(--text-faint)]'
                )}
              >
                {tab.icon}
                <span className="text-[10px] font-medium">{tab.label}</span>
              </Link>
            );
          })}

          {/* More button */}
          <button
            onClick={() => setShowMore(!showMore)}
            className={cn(
              'flex flex-col items-center justify-center gap-0.5 min-w-[56px] h-full px-2 transition-colors active:scale-[0.92]',
              isMoreActive || showMore ? 'text-[var(--accent)]' : 'text-[var(--text-faint)]'
            )}
          >
            <svg className="w-5 h-5" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.5}>
              <path strokeLinecap="round" strokeLinejoin="round" d="M3.75 6.75h16.5M3.75 12h16.5m-16.5 5.25h16.5" />
            </svg>
            <span className="text-[10px] font-medium">More</span>
          </button>
        </div>
      </nav>
    </>
  );
}
